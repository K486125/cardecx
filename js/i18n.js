let _currentLang = localStorage.getItem('cb_lang') || 'en';

function t(key) {
  return (I18N[_currentLang] || I18N.en)[key] ?? I18N.en[key] ?? key;
}

/** 카드 이름/설명 번역 (fallback: 카드 정의 원본 → 키 문자열) */
function tCard(cardId, field) {
  const key        = `card_${cardId}_${field}`;
  const translated = (I18N[_currentLang] || I18N.en)[key] ?? I18N.en[key];
  if (translated !== undefined) return translated;
  // 번역 없으면 CARD_DEFINITIONS 원본 사용
  if (typeof CARD_DEFINITIONS !== 'undefined' && CARD_DEFINITIONS[cardId]) {
    return CARD_DEFINITIONS[cardId][field] ?? key;
  }
  return key;
}

function setLang(lang) {
  if (!I18N[lang]) return;
  _currentLang = lang;
  localStorage.setItem('cb_lang', lang);
}

function getLang() {
  return _currentLang;
}

/** [data-i18n] 요소의 textContent, [data-i18n-placeholder] 요소의 placeholder를 현재 언어로 적용 */
function applyI18n(root) {
  const el = root || document;
  el.querySelectorAll('[data-i18n]').forEach(node => {
    node.textContent = t(node.dataset.i18n);
  });
  el.querySelectorAll('[data-i18n-placeholder]').forEach(node => {
    node.placeholder = t(node.dataset.i18nPlaceholder);
  });
}
